#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.md from `cargo metadata` (name, version, license, repository)."""
import json, subprocess, sys, collections

meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"], text=True))
deps = sorted((p for p in meta["packages"] if p["source"]), key=lambda p: (p["name"], p["version"]))
by_license = collections.Counter(p.get("license") or "UNKNOWN" for p in deps)

out = ["# Third-party licenses", "",
       "rdownloader itself is MIT licensed (see `LICENSE`). It is built from the Rust crates below, each under its own license.",
       "This file is generated by `scripts/third-party.py` from `Cargo.lock`; regenerate it after changing dependencies.", "",
       f"**{len(deps)} crates.** Licenses in use:", ""]
out += [f"- {n} × {l}" for l, n in by_license.most_common()]
out += ["", "| Crate | Version | License | Repository |", "| --- | --- | --- | --- |"]
for p in deps:
    out.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'see crate'} | {p.get('repository') or ''} |")
open(sys.argv[1] if len(sys.argv) > 1 else "THIRD_PARTY_LICENSES.md", "w").write("\n".join(out) + "\n")
